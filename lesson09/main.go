package main

import (
	"fmt"
	"time"
)

// Герой бьёт дракона автоматически, раз в секунду.
// Но на всё про всё даётся 10 секунд!
// select помогает программе следить СРАЗУ за двумя событиями:
// за ударом героя и за тикающими часами.

func main() {
	dragonHP := 30
	const heroDamage = 4

	// Каждую секунду в этот канал прилетает текущее время.
	// Это «пульс» героя: раз в секунду — один удар.
	hits := time.Tick(time.Second)

	// time.After ждёт указанное время и отправит ОДНО сообщение.
	// Как будто кто-то завёл будильник: через 10 секунд — звонок.
	timer := time.After(10 * time.Second)

	for dragonHP > 0 {
		// select ждёт, ПОКА ХОТЬ ОДИН канал не пришлёт сообщение,
		// и выполняет его ветку. Похоже на switch, но для каналов.
		select {
		case <-hits:
			dragonHP = dragonHP - heroDamage
			fmt.Println("Герой бьёт! Дракону осталось", dragonHP, "HP")
		case <-timer:
			// Сюда попадём, только если будильник зазвенел РАНЬШЕ победы
			fmt.Println("Время вышло! Дракон улетел за облака...")
			return // выход из main — программа заканчивается
		}
	}

	fmt.Println("Победа! Дракон повержен!")

	// --- Маленькая практика ---
	// 1. Сбалансируйте игру: поменяйте HP дракона, урон героя и время.
	//    При каких числах победа невозможна? Проверьте!
	// 2. Добавьте третий канал: time.Tick(3 сек) — дракон лечится на 5 HP.
	//    select умеет ждать хоть десять каналов!
	// 3. Усложнение: запомните time.Now() в начале и выведите,
	//    за сколько секунд герой победил (time.Since).
}
