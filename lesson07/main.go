package main

import "fmt"

// Hero — карточка игрового персонажа (уже знакомо из прошлых уроков)
type Hero struct {
	Name string
	HP   int
}

// Метод — это функция, "привязанная" к структуре.
// Внутри метода h — сам герой, у которого его вызвали.
// Пишем (h *Hero) перед именем, и h работает как привычный player.
func (h *Hero) Hit(damage int) {
	h.HP = h.HP - damage
	if h.HP < 0 {
		h.HP = 0
	}
	fmt.Println(h.Name, "получил", damage, "урона. Осталось", h.HP, "HP")
}

func (h *Hero) Heal(amount int) {
	h.HP = h.HP + amount
	fmt.Println(h.Name, "выпил зелье: +", amount, "HP. Теперь", h.HP)
}

func (h Hero) IsAlive() bool {
	// Если метод ничего не меняет, звёздочка (*) не обязательна
	return h.HP > 0
}

func main() {
	hero := Hero{Name: "Алёша", HP: 20}

	// Словарь (map): значение лежит не по номеру, а по ключу.
	// map[строка]число — ключи строки, значения числа.
	prices := map[string]int{
		"меч":     50,
		"зелье":   10,
		"щит":     30,
		"браслет": 999,
	}

	// Читаем из словаря по ключу — как инвентарь по имени вещи
	fmt.Println("Зелье стоит", prices["зелье"], "золота")

	// Проверяем, есть ли ключ в словаре.
	// Второе значение (ok) говорит, нашёлся он или нет.
	// Без проверки отсутствующий ключ вернёт просто 0.
	price, ok := prices["кольцо"]
	if ok {
		fmt.Println("Кольцо стоит", price)
	} else {
		fmt.Println("Такого артефакта в магазине нет")
	}

	// Вместо "полный магазин" — разбрасываем всё на полки
	fmt.Println("--- Список товаров ---")
	for item, cost := range prices {
		// Порядок случайный: словарь не помнит, кто был первым
		fmt.Println(item, "-", cost, "золота")
	}

	// Добавляем новый товар и убираем старый
	prices["кольцо"] = 15
	delete(prices, "браслет")

	// Методы вызываются через точку — hero сам действует,
	// не нужно передавать его первым аргументом
	hero.Hit(12)
	hero.Heal(5)

	if hero.IsAlive() {
		fmt.Println(hero.Name, "жив и готов к бою!")
	} else {
		fmt.Println("Герой пал...")
	}

	// --- Маленькая практика ---
	// 1. Добавьте методу Hit шанс уклонения (math/rand уже знаком).
	// 2. Добавьте в словарь свой артефакт и выведите весь магазин.
	// 3. Напишите метод LevelUp: +10 к максимальному HP.
}
